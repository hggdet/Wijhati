import SwiftUI

/// Launch intro designed by the user: a black or white screen (following
/// the device appearance) where dots fly in from every edge of the screen
/// and assemble into a dotted world map — black dots on white in light
/// mode, white dots on black in dark mode — then the map lingers a while
/// before the app fades in. The dot grid was rasterised from Natural
/// Earth country outlines.
struct WorldIntroView: View {
    @Environment(\.colorScheme) private var scheme
    @State private var assembled = false
    @State private var showTitle = false

    private struct Dot {
        let col: Int
        let row: Int
        let edge: Int
        let frac: CGFloat
        let delay: Double
    }

    private static let cols = 88
    private static let rows = 44
    private static let mask: [String] = [
        ".......................######....#####..................................................",
        "..................#..####..############........##..................#....................",
        "...............###.#.#.......##########...................##.......#####......#.........",
        ".............####..#..##.......########..................#...#..############..#.........",
        "....######.####.###.##.#.###....######..........####.......#.########################.##",
        "##.####################...#.#..####...##.......#####..##################################",
        "....#################......#....##............##.#######################################",
        "....##....###########....##..................###..##############################.#.#....",
        "............###########..####.................##.#############################....##....",
        "............############.#####.............#.##################################...#.....",
        "..............###############...............##################################..........",
        "..............###############...............#######.####.#####################..........",
        "..............#############...............###...###...##.####################.#.........",
        "..............############................##.....#######.################.#...#.........",
        "..............###########.................#.###..#...#####################.#.#..........",
        "...............##########.................#####......#####################..#...........",
        "................######.#..................################################..............",
        "................####.....................###########.###.################...............",
        "..................##....................##################...#############..............",
        "..................##..#..#..............#############.####....###..###..................",
        "....................##..................#################.....##...###...#..............",
        "......................##................##############.#......##....###.................",
        ".......................#...##...........################.......#........................",
        ".........................#####...........###############............#.....#.............",
        ".........................######...............##########................#...............",
        "........................########..............#########.............#..###..............",
        "........................##########............########...............#.#.#..###.........",
        "........................###########............######.........................###.......",
        ".........................##########............#######....................#.............",
        ".........................##########............#######......................#...........",
        "..........................########.............#######.#..................###..#........",
        "...........................#######.............######..#..................######........",
        "...........................#######.............######..#................#########.......",
        "...........................#####................####....................#########.......",
        "...........................#####................####....................##########......",
        "...........................####.................###.....................###..####.......",
        "..........................####................................................###.....#.",
        "..........................####.........................................................#",
